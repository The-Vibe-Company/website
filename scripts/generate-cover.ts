/**
 * Generates an article cover in the house art direction, the same one the
 * `generate-brand-image-marketing` skill produces: a single The Vibe Company
 * mascot, stylized 3D clay render, warm saturated palette, no text.
 *
 * It calls the Azure OpenAI image *edit* endpoint with the mascot reference
 * PNG attached, so the character stays identical from one cover to the next
 * rather than drifting on every generation, then writes the result as
 * `public/images/resources/<slug>/cover-mascotte.webp`.
 *
 * The API key is read from the environment only (`AZURE_OPENAI_API_KEY`, or
 * `OPENAI_API_KEY` as a fallback). Put it in `.env.local`, which bun loads
 * automatically and git ignores. Never commit a key, and never wire this
 * script into CI: covers are generated by a human who looks at the result.
 *
 * Usage:
 *   bun scripts/generate-cover.ts --slug <article-slug> --scene "<what to draw>"
 *   bun scripts/generate-cover.ts --slug <article-slug> --prompt-only
 *
 * Run `--prompt-only` first to read the composed prompt without spending a
 * generation. After generating, open the file and check the mascot against the
 * reference: black swept-back pattern on the head with a central point on the
 * forehead, black V on the chest, no golden badge. Regenerate if it drifted.
 *
 * There is no fallback cover. If the generation cannot run (no key, API down),
 * stop: do not copy another article's cover in as a "temporary" one. Every
 * article needs its own image, and `bun run content:covers-check` fails CI on
 * any two articles whose covers have the same bytes.
 */
import { promises as fs } from 'node:fs'
import path from 'node:path'
import sharp from 'sharp'

import { parseFrontmatter } from '../src/lib/parse-frontmatter'

const ROOT = process.cwd()
const ARTICLES_DIR = path.join(ROOT, 'content', 'articles')

const DEFAULT_ENDPOINT = 'https://quivr-sweden-central-resource.openai.azure.com/openai/v1'
const DEFAULT_DEPLOYMENT = 'gpt-image-2-1'
const DEFAULT_MASCOT = path.join('public', 'brand', 'mascot-reference.png')

/** Covers are wide editorial headers; the og-image gate wants a ~1.5:1 ratio. */
const SIZE = '1536x1024'
const WEBP_QUALITY = 80

/**
 * The shared art direction. Constant across every brand visual, in English
 * because the image models respond better to it. Only the scene changes.
 */
const ART_DIRECTION = `Stylized 3D render, premium mobile game key art, blending Pixar character appeal with Clash of Clans / Clash Royale game art. Soft matte clay-like sculpted surfaces, smooth rounded clean forms, slightly exaggerated friendly proportions, expressive readable features. Warm rich saturated color palette. Soft cinematic studio lighting, gentle global illumination, subtle rim light, soft ambient occlusion, no harsh shadows. Crisp polished details, professional high-end finish. Charming, heroic, lively mood.`

/**
 * The mascot, described in full. Describing the head as "a winged emblem" makes
 * the model add a golden badge, which is not the character: the pattern is
 * painted straight onto the head.
 */
const MASCOT = `The hero is the reference mascot, exactly one, identical to the reference image: small smooth glossy white clay character, big round shiny black eyes, small smile, a glossy BLACK swept-back multi-pointed pattern painted directly on top of its head with a central point on the forehead, a black V-shaped vest on its chest with black shoulders, rounded white arms and legs, soft orange glow. No badge, no golden emblem, nothing attached to its forehead.`

const FRAMING = `Single clear focal point, readable at thumbnail size.`

const NEGATIVE = `No text, no letters, no logos, no watermark, not photorealistic.`

type Options = {
  slug: string
  scene?: string
  theme?: string
  mascot: string
  out: string
  promptOnly: boolean
  force: boolean
}

function fail(message: string): never {
  console.error(`[fail] ${message}`)
  process.exit(1)
}

function parseArgs(argv: string[]): Options {
  const values = new Map<string, string>()
  const flags = new Set<string>()

  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index]
    if (!arg.startsWith('--')) continue
    const key = arg.slice(2)
    if (key === 'prompt-only' || key === 'force') {
      flags.add(key)
      continue
    }
    const value = argv[index + 1]
    if (value == null || value.startsWith('--')) fail(`--${key} needs a value.`)
    values.set(key, value)
    index += 1
  }

  const slug = values.get('slug')
  if (!slug) {
    fail('--slug is required, e.g. `--slug ia-donnees-de-sante-hds`.')
  }

  return {
    slug,
    scene: values.get('scene'),
    theme: values.get('theme'),
    mascot: values.get('mascot') ?? process.env.TVC_MASCOT_REFERENCE ?? DEFAULT_MASCOT,
    out:
      values.get('out') ??
      path.join('public', 'images', 'resources', slug, 'cover-mascotte.webp'),
    promptOnly: flags.has('prompt-only'),
    force: flags.has('force'),
  }
}

/** Title and summary of the article, used when no explicit theme is given. */
async function readArticleTheme(slug: string): Promise<string | null> {
  const file = path.join(ARTICLES_DIR, `${slug}.md`)
  let raw: string
  try {
    raw = await fs.readFile(file, 'utf8')
  } catch {
    return null
  }
  const { data } = parseFrontmatter(raw)
  const parts = [data.title, data.summary].map((part) => part?.trim()).filter(Boolean)
  return parts.length > 0 ? parts.join(' — ') : null
}

function composePrompt({ scene, theme }: { scene?: string; theme: string }): string {
  // A `--scene` is the editorial choice: one concrete, readable metaphor. Without
  // one, fall back to the article's own words and ask for a single metaphor
  // rather than a literal illustration of the title.
  const subject = scene
    ? scene.trim().replace(/\.?$/, '.')
    : `The mascot illustrates this article with one single clear visual metaphor, not a literal scene and not a crowded composition: ${theme}`

  return [
    ART_DIRECTION,
    'Wide editorial article header.',
    MASCOT,
    subject,
    'Three-quarter wide shot, soft gradient background.',
    FRAMING,
    NEGATIVE,
  ].join(' ')
}

async function generate(prompt: string, mascotPath: string): Promise<Buffer> {
  const apiKey = process.env.AZURE_OPENAI_API_KEY ?? process.env.OPENAI_API_KEY
  if (!apiKey) {
    fail(
      'no API key. Set AZURE_OPENAI_API_KEY (or OPENAI_API_KEY) in .env.local — never commit it. ' +
        "Do not copy another article's cover as a placeholder: CI rejects duplicated covers.",
    )
  }

  const endpoint = (process.env.AZURE_OPENAI_IMAGE_ENDPOINT ?? DEFAULT_ENDPOINT).replace(/\/$/, '')
  const deployment = process.env.AZURE_OPENAI_IMAGE_DEPLOYMENT ?? DEFAULT_DEPLOYMENT

  let mascot: Buffer
  try {
    mascot = await fs.readFile(mascotPath)
  } catch {
    fail(
      `mascot reference not found at ${mascotPath}. It ships with the repo at ` +
        'public/brand/mascot-reference.png — restore it, or point --mascot/TVC_MASCOT_REFERENCE at another copy.',
    )
  }

  const form = new FormData()
  form.append('model', deployment)
  form.append('prompt', prompt)
  form.append('size', SIZE)
  form.append('n', '1')
  form.append('image', new File([new Uint8Array(mascot)], 'mascot.png', { type: 'image/png' }))

  console.log(`[info] generating with ${deployment} at ${endpoint} (this takes a minute or two)…`)

  const response = await fetch(`${endpoint}/images/edits`, {
    method: 'POST',
    headers: {
      // Azure accepts either header on the /openai/v1 surface.
      'api-key': apiKey,
      Authorization: `Bearer ${apiKey}`,
    },
    body: form,
  })

  if (!response.ok) {
    const body = await response.text()
    fail(`image API returned ${response.status}: ${body.slice(0, 500)}`)
  }

  const payload = (await response.json()) as { data?: { b64_json?: string }[] }
  const encoded = payload.data?.[0]?.b64_json
  if (!encoded) fail('image API returned no image data.')

  return Buffer.from(encoded, 'base64')
}

async function main(): Promise<void> {
  const options = parseArgs(process.argv.slice(2))

  const theme = options.theme ?? (await readArticleTheme(options.slug))
  if (!theme && !options.scene) {
    fail(
      `no theme for "${options.slug}": content/articles/${options.slug}.md was not found. ` +
        'Pass --theme "<subject>" or --scene "<what to draw>".',
    )
  }

  const prompt = composePrompt({ scene: options.scene, theme: theme ?? '' })

  console.log(`\n[prompt]\n${prompt}\n`)

  if (options.promptOnly) {
    console.log('[ok] prompt only, nothing generated.')
    return
  }

  const outPath = path.resolve(ROOT, options.out)
  if (!options.force) {
    try {
      await fs.access(outPath)
      fail(`${options.out} already exists. Pass --force to overwrite it.`)
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error
    }
  }

  const png = await generate(prompt, path.resolve(ROOT, options.mascot))

  await fs.mkdir(path.dirname(outPath), { recursive: true })
  await sharp(png).webp({ quality: WEBP_QUALITY }).toFile(outPath)

  const { width, height, size } = await sharp(outPath).metadata()
  console.log(`[ok] wrote ${options.out} (${width}x${height}, ${Math.round((size ?? 0) / 1024)} KB)`)
  console.log(
    '[next] open the file and check the mascot: black swept-back pattern on the head with a ' +
      'central point on the forehead, black V on the chest, NO golden badge. Regenerate if it drifted.',
  )
  console.log('[next] then run `bun run images:optimize` and `bun run content:check`.')
}

main().catch((error) => {
  console.error(error)
  process.exit(1)
})
